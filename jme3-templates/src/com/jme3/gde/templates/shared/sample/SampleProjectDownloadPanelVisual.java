    private void downloadButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_downloadButtonActionPerformed
        statusField.setText(org.openide.util.NbBundle.getMessage(SampleProjectDownloadPanelVisual.class, "SampleProjectDownloadPanelVisual.downloading"));
        downloadButton.setEnabled(false);
        panel.downloadAsync(result -> {
            javax.swing.SwingUtilities.invokeLater(() -> {
                downloadButton.setEnabled(true);
                if (result) {
                    statusField.setText(org.openide.util.NbBundle.getMessage(SampleProjectDownloadPanelVisual.class, "SampleProjectDownloadPanelVisual.downloadSuccess"));
                } else {
                    statusField.setText(org.openide.util.NbBundle.getMessage(SampleProjectDownloadPanelVisual.class, "SampleProjectDownloadPanelVisual.downloadFailed"));
                }
                panel.fireChangeEvent();
            });
        });
    }//GEN-LAST:event_downloadButtonActionPerformed

