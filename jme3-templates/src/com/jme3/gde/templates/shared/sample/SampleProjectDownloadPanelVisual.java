    boolean valid(WizardDescriptor wizardDescriptor) {
        if (!panel.isDownloaded()) {
            wizardDescriptor.putProperty("WizardPanel_errorMessage",
                    org.openide.util.NbBundle.getMessage(SampleProjectDownloadPanelVisual.class, "SampleProjectDownloadPanel.errorNotDownloaded"));
            return false;
        }
        wizardDescriptor.putProperty("WizardPanel_errorMessage", "");
        return true;
    }

